SELECT
  F4211.SDPDDJ F4211_SDPDDJ,
  F4211.SDDOCO F4211_SDDOCO,
  F4211.SDSHAN F4211_SDSHAN,
  F4211.SDVR01 F4211_SDVR01,
  F4211.SDLITM F4211_SDLITM,
  F4211.SDAN8 F4211_SDAN8,
  F4211.SDMCU F4211_SDMCU,
  F4211.SDPA8 F4211_SDPA8,
  SUM(F4211.SDUORG) ReportColumn1,
  SUM(F4211.SDSOBK) ReportColumn2,
  SUM(F4211.SDSOCN) ReportColumn3,
  SUM(F4211.SDQTYT) ReportColumn4,
  SUM(F4211.SDAEXP) ReportColumn5,
  F0010.CCCRCD DomesticCurrency
FROM
  PRODDTA.F4211 F4211
  INNER JOIN PRODDTA.F0010 F0010 ON F0010.CCCO = F4211.SDKCOO
WHERE
  (
    ((F4211.SDNXTR BETWEEN N'525' AND N'573'))
    AND ((F4211.SDPA8 IN (20022576)))
  )
GROUP BY
  F4211.SDPDDJ,
  F4211.SDDOCO,
  F4211.SDSHAN,
  F4211.SDVR01,
  F4211.SDLITM,
  F4211.SDAN8,
  F4211.SDMCU,
  F4211.SDPA8,
  F0010.CCCRCD
UNION ALL
