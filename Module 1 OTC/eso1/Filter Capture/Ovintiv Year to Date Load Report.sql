  INNER JOIN PRODDTA.F0010 F0010 ON F0010.CCCO = F4211.SDKCOO
WHERE
  (
    (
      (
        ((F4211.SDADDJ >= 126001))
        AND (
          (
            NOT (F4211.SDLITM IN (N'MISC BILLING             '))
          )
